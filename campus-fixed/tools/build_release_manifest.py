#!/usr/bin/env python3
"""Build or verify RELEASE_MANIFEST.json for the campus release tree.

Build:
    python tools/build_release_manifest.py --root .

Verify a released archive against the manifest it ships:
    python tools/build_release_manifest.py --root . --verify 偷闲天大版-1.8满分版.zip

The manifest lists every shipped file with its byte size and SHA-256, sorted by
path, so a downloaded ZIP can be checked entry by entry: the recorded SHA-256
must match the decompressed bytes and the recorded CRC-32 must match the ZIP
directory entry. A truncated, re-packed or hand-edited archive cannot pass
silently.

Two classes of path are treated differently:

* Ignored — the manifest itself, VCS metadata, dependency directories and
  Python bytecode/cache directories. These never ship.
* Refused — runtime secrets (``data/.server-secret``) and SQLite
  ``-wal``/``-shm`` sidecars. The builder stops instead of quietly hashing
  them, because a release that contains a signing key or a half-checkpointed
  journal is a defect, not a file listing.

Verification reads entry names the way the archive intends them to be read, not
the way ``zipfile`` guesses. A ZIP entry carries its name as bytes and declares
its encoding only through the UTF-8 flag (bit 0x800). Python's ``zipfile`` sets
that flag when it writes a non-ASCII name, so this project's own archives are
unambiguous; other tools routinely omit it, and then ``zipfile`` decodes the
bytes as cp437 and a Chinese filename arrives as mojibake — ``源码导航.md``
reads back as ``µ║Éτáüσ»╝Φê¬.md``. An archive like that is not corrupt, just
undeclared, so ``archive_entry_name`` re-decodes it as UTF-8 when the flag is
absent. Without that, the verifier reports the same file as both absent from the
archive and unexpected in it, and a reviewer following the documented command is
told a perfectly good ZIP failed.

The header records which release this tree was derived from, so lineage stays
verifiable after the baseline directory is gone.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import zipfile
import zlib
from pathlib import Path

MANIFEST_NAME = "RELEASE_MANIFEST.json"
PUBLIC_SAMPLE = "data/campus.sqlite3"

# Bumped when a new release is cut from this tree.
PRODUCT_VERSION = "1.8.0"
CONTRACT_VERSION = "1.5.0"
DERIVED_FROM_VERSION = "1.7.0"
DERIVED_FROM_MANIFEST_SHA256 = "237f8d9780affccc08204f36c89311bbb26df227af71fd99be4f32fb02cce9cc"

IGNORED_DIRS = {
    ".git",
    ".hg",
    ".svn",
    "node_modules",
    "__pycache__",
    ".pytest_cache",
    ".venv",
    "venv",
    ".mypy_cache",
    ".ruff_cache",
}
# Scratch directories, mirroring .gitignore. They are never deliverables, and a
# run that left one behind must not silently widen the manifest. `.campus`,
# `.review` and `.test-temp` are written by the test fixtures; `.snapshot-tmp` is
# an ad-hoc working directory -- round 10 built the public data snapshot in one
# and left its helper script behind, which the builder then hashed into the
# manifest because it had no rule for the name.
IGNORED_DIR_PREFIXES = (".campus", ".review", ".test-temp", ".snapshot-tmp")
# Directories identified by their path, not their name: an operator-mode
# instance's live database and the relay's regenerable feed output. `.gitignore`
# cannot express these for a release -- the builder has its own walk -- so the
# exclusion lives here, where the manifest is produced.
IGNORED_RELATIVE_DIRS = ("data-operator", "deploy/operator/out")
IGNORED_SUFFIXES = (".pyc", ".pyo")
IGNORED_NAMES = {MANIFEST_NAME, ".DS_Store"}

REFUSED_NAMES = {".server-secret"}
REFUSED_SUFFIXES = ("-wal", "-shm")
# A live operator session cookie authenticates as the deployment's operator
# exactly like a signing key does, so a build that finds one stops instead of
# hashing it into a release. Delete the file (it is regenerated by logging in)
# and rebuild.
REFUSED_RELATIVE_PATHS = frozenset({"deploy/operator/session.json"})


def _is_session_credential(relative: str) -> bool:
    """Any file that names itself a session cache carries a live cookie.

    ``IGNORED_RELATIVE_DIRS`` drops scratch *directories*, but a scratch *file*
    at the repository root (".test-temp-student-session.json") is not a
    directory: one shipped in a release. The shape of the name is the signal, so
    every "*-session.json" / "session.json" is refused wherever it lives.
    """
    name = relative.rsplit("/", 1)[-1].lower()
    return name == "session.json" or name.endswith("-session.json") or name.endswith("_session.json")

CHUNK = 1 << 20


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sort_key(relative: str):
    """Case-insensitive, per-segment ordering: ``verification/a/...`` before
    ``VERIFICATION.json``. Keeps the listing stable across filesystems whose
    directory enumeration order differs."""
    return tuple(segment.lower() for segment in relative.split("/"))


def iter_shipped(root: Path):
    """Yield (relative posix path, absolute path) for every shipped file."""
    for dirpath, dirnames, filenames in os.walk(root):
        relative_dir = Path(dirpath).relative_to(root).as_posix()
        if relative_dir == ".":
            relative_dir = ""
        if any(relative_dir == ignored or relative_dir.startswith(ignored + "/") for ignored in IGNORED_RELATIVE_DIRS):
            # Prune: the directory and everything under it is machine-local.
            dirnames[:] = []
            continue
        dirnames[:] = sorted(
            name
            for name in dirnames
            if name not in IGNORED_DIRS and not name.startswith(IGNORED_DIR_PREFIXES) and not name.startswith(".tmp")
        )
        for name in sorted(filenames):
            if name in IGNORED_NAMES or name.endswith(IGNORED_SUFFIXES):
                continue
            # Scratch files, not just scratch directories. ".test-temp-srv9.log"
            # at the repository root is not a directory, so the directory filter
            # left it alone and a server log shipped inside the release. Anything
            # named like scratch is scratch, wherever it lives — except a session
            # file, which falls through to the refuse check so a live cookie
            # stops the build loudly instead of being quietly filtered away.
            if name.startswith(".tmp") or (
                name.startswith(IGNORED_DIR_PREFIXES) and not _is_session_credential(name)
            ):
                continue
            path = Path(dirpath) / name
            yield path.relative_to(root).as_posix(), path


def build(root: Path, product_version: str, contract_version: str) -> dict:
    entries: list[dict] = []
    refused: list[str] = []
    for relative, path in iter_shipped(root):
        name = Path(relative).name
        if (
            relative in REFUSED_RELATIVE_PATHS
            or name in REFUSED_NAMES
            or relative.endswith(REFUSED_SUFFIXES)
            or _is_session_credential(relative)
        ):
            refused.append(relative)
            continue
        entries.append(
            {
                "path": relative,
                "bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
        )
    if refused:
        raise SystemExit(
            "refusing to build: runtime artifacts must never ship -> "
            + ", ".join(refused)
            + "\nDelete them (a signing key or a live WAL is a defect), then rebuild."
        )
    entries.sort(key=lambda entry: sort_key(entry["path"]))
    sample = root / PUBLIC_SAMPLE
    if not sample.is_file():
        raise SystemExit(f"refusing to build: public sample {PUBLIC_SAMPLE} is missing")
    return {
        "product_version": product_version,
        "contract_version": contract_version,
        "derived_from_version": DERIVED_FROM_VERSION,
        "derived_from_manifest_sha256": DERIVED_FROM_MANIFEST_SHA256,
        "private_data_removed": True,
        "public_sample_sha256": sha256_file(sample),
        "file_count": len(entries),
        "files": entries,
    }


UTF8_FLAG = 0x800


def archive_entry_name(info: zipfile.ZipInfo) -> str:
    """The entry's name, decoded the way the archive meant it.

    An archive that omits the UTF-8 flag stores a non-ASCII name as bytes that
    ``zipfile`` hands back decoded as cp437. Re-decode those bytes as UTF-8 when
    the flag is absent, and keep what ``zipfile`` returned when that fails, so an
    archive whose names genuinely are cp437 is left alone. See the module
    docstring for why this matters.
    """
    name = info.filename
    if info.flag_bits & UTF8_FLAG:
        return name
    try:
        return name.encode("cp437").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return name


def verify(root: Path, archive: Path) -> int:
    manifest_path = root / MANIFEST_NAME
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        # A reviewer pointing at the wrong tree gets one line and a non-zero
        # exit, never a traceback. That is the whole contract.
        print(f"FAIL: cannot read {manifest_path.name}: {error}", file=sys.stderr)
        return 1
    recorded = {entry["path"]: entry for entry in manifest["files"]}
    problems: list[str] = []
    checked = 0

    # BadZipFile can surface at open time (not an archive at all) or at read
    # time (a member fails its CRC check). Both mean the same thing to the
    # reviewer, so both become one line instead of a traceback (AI_PENDING_TASKS
    # T15). The archive is still rejected either way -- exit 1, and
    # package_release.py never writes its .sha256 sidecar.
    try:
        with zipfile.ZipFile(archive) as bundle:
            seen: set[str] = set()
            for info in bundle.infolist():
                if info.is_dir():
                    continue
                name = archive_entry_name(info)
                if name == MANIFEST_NAME or name.endswith("/" + MANIFEST_NAME):
                    # The manifest ships inside the archive but cannot list itself.
                    continue
                key = name if name in recorded else None
                if key is None:
                    _, _, tail = name.partition("/")
                    if tail and tail in recorded:
                        key = tail
                if key is None:
                    problems.append(f"unexpected entry in archive: {name}")
                    continue
                seen.add(key)
                raw = bundle.read(info)
                entry = recorded[key]
                actual = hashlib.sha256(raw).hexdigest()
                if actual != entry["sha256"]:
                    problems.append(f"sha256 mismatch: {key}")
                if len(raw) != entry["bytes"]:
                    problems.append(f"size mismatch: {key} ({len(raw)} != {entry['bytes']})")
                if info.CRC != zlib.crc32(raw) & 0xFFFFFFFF:
                    problems.append(f"crc mismatch: {key}")

            missing = sorted(set(recorded) - seen)
            if missing:
                problems.append(
                    f"{len(missing)} manifest file(s) absent from archive: "
                    + ", ".join(missing[:5])
                    + ("..." if len(missing) > 5 else "")
                )
            checked = len(seen)
    except zipfile.BadZipFile as error:
        print(f"FAIL: {archive.name} is not a readable archive: {error}", file=sys.stderr)
        return 1

    if problems:
        print(f"FAIL: {len(problems)} problem(s) in {archive.name}", file=sys.stderr)
        for problem in problems[:40]:
            print("  - " + problem, file=sys.stderr)
        if len(problems) > 40:
            print(f"  ... and {len(problems) - 40} more", file=sys.stderr)
        return 1

    print(
        f"OK: {checked} files verified against {MANIFEST_NAME} "
        f"(product {manifest['product_version']}, "
        f"sample {manifest['public_sample_sha256'][:12]}...)"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=".", type=Path, help="release tree root (default: current directory)")
    parser.add_argument("--verify", type=Path, default=None, help="check an existing ZIP against the manifest and exit")
    parser.add_argument("--product-version", default=PRODUCT_VERSION)
    parser.add_argument("--contract-version", default=CONTRACT_VERSION)
    args = parser.parse_args()

    root = args.root.resolve()
    if args.verify is not None:
        return verify(root, args.verify)

    manifest = build(root, args.product_version, args.contract_version)
    target = root / MANIFEST_NAME
    # newline="\n" is load-bearing: Path.write_text() translates "\n" to
    # os.linesep, so on Windows a rebuild silently rewrote every line of the
    # manifest as CRLF and buried the real change in a whole-file diff. The
    # manifest ships to other platforms, so pin it to LF.
    with target.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(
        f"wrote {target.name}: {manifest['file_count']} files, "
        f"product {manifest['product_version']}, "
        f"sample {manifest['public_sample_sha256'][:12]}..."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
